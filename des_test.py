import re

# 原始字符串
task_text = """
任务指令：
1. 启动与进入： 打开滴滴出行进入主页。
2. 触发搜索： 在主页点击“您想去哪儿”搜索框（坐标约在 327, 500）。
  - 异常处理： 若进入“预约打车”或“立即选车”页面，请点击返回键回到主页重试，确保进入的是带键盘的“目的地搜索页面”。
3. 输入目的地： 在搜索框输入“民发天地东门”。
4. 选择目标： 在搜索结果列表中，点击最匹配的选项（通常是第一项）。
...（后续省略）
"""

# 使用正则表达式提取引号内的内容
# 这里的逻辑是：匹配 “输入“ 之后，到下一个 ” 结束之前的所有字符
match = re.search(r'输入“([^”]+)”', task_text)

if match:
    destination = match.group(1)
    print(f"提取的目的地为: {destination}")
else:
    print("未找到目的地信息")

